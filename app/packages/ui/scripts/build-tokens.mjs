// Generates tokens.css from tokens/tokens.json: semantic variables in hex and OKLCH for light (:root)
// and dark (.dark), shadcn/ui aliases, the type scale as utility classes, and the font stacks.
// Run: node scripts/build-tokens.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, "../tokens/tokens.json"), "utf8"));

// ---- colour maths (sRGB -> OKLCH) ----
const hexToRgb = (hex) => {
  const h = hex.replace("#", "");
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
};
const lin = (c) => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
export function hexToOklch(hex) {
  const [r, g, b] = hexToRgb(hex).map(lin);
  const l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b;
  const m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b;
  const s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b;
  const l_ = Math.cbrt(l), m_ = Math.cbrt(m), s_ = Math.cbrt(s);
  const L = 0.2104542553 * l_ + 0.793617785 * m_ - 0.0040720468 * s_;
  const A = 1.9779984951 * l_ - 2.428592205 * m_ + 0.4505937099 * s_;
  const B = 0.0259040371 * l_ + 0.7827717662 * m_ - 0.808675766 * s_;
  const C = Math.sqrt(A * A + B * B);
  let H = (Math.atan2(B, A) * 180) / Math.PI;
  if (H < 0) H += 360;
  return `oklch(${(L * 100).toFixed(2)}% ${C.toFixed(4)} ${C < 0.0005 ? 0 : H.toFixed(2)})`;
}

const shadcn = {
  background: "bg", foreground: "text", card: "surface", "card-foreground": "text", popover: "surface",
  "popover-foreground": "text", primary: "primary", "primary-foreground": "primary-foreground",
  secondary: "surface-2", "secondary-foreground": "text", muted: "surface-2", "muted-foreground": "text-muted",
  accent: "accent-solid", "accent-foreground": "accent-foreground", destructive: "danger-solid",
  "destructive-foreground": "danger-foreground", border: "border", input: "input", ring: "focus",
  "chart-1": "chart-1", "chart-2": "chart-2", "chart-3": "chart-3", "chart-4": "chart-4", "chart-5": "chart-5",
};

function block(selector, theme) {
  const lines = [`${selector} {`];
  for (const [k, v] of Object.entries(theme)) {
    lines.push(`  --${k}: ${v};`);
    lines.push(`  --${k}-oklch: ${hexToOklch(v)};`);
  }
  for (const [alias, k] of Object.entries(shadcn)) if (alias !== k) lines.push(`  --${alias}: var(--${k});`);
  lines.push(`  --radius: ${tokens.radius.control}px;`);
  lines.push(`  --radius-card: ${tokens.radius.card}px;`);
  lines.push(`  --radius-modal: ${tokens.radius.modal}px;`);
  lines.push("}");
  return lines.join("\n");
}

let css = `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */\n`;
css += `/* Palette "${tokens.name}". ${tokens.source}. */\n\n`;
css += block(":root", tokens.light) + "\n\n";
css += block(".dark", tokens.dark) + "\n\n";
css += `:root {\n`;
for (const [k, v] of Object.entries(tokens.fonts)) css += `  --font-${k}: ${v};\n`;
css += `  --prompter-bg: ${tokens.prompter.bg};\n  --prompter-text: ${tokens.prompter.text};\n`;
css += `  --rail: ${tokens.layout.rail}px;\n  --rail-collapsed: ${tokens.layout.railCollapsed}px;\n  --content-max: ${tokens.layout.contentMax}px;\n  --right-panel: ${tokens.layout.rightPanel}px;\n`;
tokens.space.forEach((v, i) => (css += `  --space-${i + 1}: ${v}px;\n`));
css += `}\n\n`;
css += `body { background: var(--bg); color: var(--text); font-family: var(--font-ui); font-size: 16px; line-height: 24px; }\n`;
css += `.tabular { font-variant-numeric: tabular-nums; }\n`;
css += `:focus-visible { outline: 2px solid var(--focus); outline-offset: 2px; }\n\n`;
css += `/* Type scale (blueprint 11.2) */\n`;
for (const [name, t] of Object.entries(tokens.type_scale)) {
  if (name === "comment") continue;
  css += `.t-${name} { font-family: var(--font-${t.family}); font-size: ${t.size}px; line-height: ${t.line}px; font-weight: ${t.weight}; letter-spacing: ${t.tracking}em;${t.maxWidth ? ` max-width: ${t.maxWidth};` : ""} }\n`;
}
css += `\n@media (prefers-reduced-motion: reduce) { *, *::before, *::after { animation-duration: 0.001ms !important; transition-duration: 0.001ms !important; scroll-behavior: auto !important; } }\n`;

mkdirSync(join(here, "../dist"), { recursive: true });
writeFileSync(join(here, "../dist/tokens.css"), css);
console.log(`tokens.css written: ${css.split("\n").length} lines`);
